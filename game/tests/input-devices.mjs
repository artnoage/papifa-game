import assert from 'node:assert/strict';
import { createInput } from '../src/input.js';

const events = new EventTarget(), canvas = new EventTarget();
globalThis.addEventListener = events.addEventListener.bind(events);
const makePad = () => ({ connected: true, axes: [0, 0], buttons: Array.from({ length: 16 }, () => ({ pressed: false })) });
const pads = [makePad(), null, makePad()];
Object.defineProperty(globalThis, 'navigator', { value: { getGamepads: () => pads }, configurable: true });
const players = [{}, {}], match = { humans: players, human: players[0], ball: { owner: players[1] } };
const keyboard = createInput({ type: 'keyboard' }, { team: 1, liveMatch: () => match,
  pitchTarget: { canvas, at: () => ({ x: 4, z: 8 }), hide() {} } });
const pad0 = createInput({ type: 'gamepad', index: 0 }), pad2 = createInput({ type: 'gamepad', index: 2 });
const touch = createInput({ type: 'touch' }, { touch: { poll: i => { i.move.x = 0.5; }, reset() {} } });
const key = (type, code) => events.dispatchEvent(Object.assign(new Event(type), { code }));
const pointer = (type, button) => canvas.dispatchEvent(Object.assign(new Event(type), { pointerType: 'mouse', button }));
key('keydown', 'KeyW'); pointer('pointerdown', 0);
pads[0].axes = [0.8, 0]; pads[0].buttons[0].pressed = true;
pads[2].axes = [0, 0.7]; pads[2].buttons[9].pressed = true;
const k = keyboard.poll(), a = pad0.poll(), b = pad2.poll(), finger = touch.poll();
assert.deepEqual(k.move, { x: 0, z: -1 }); assert.ok(k.shootPressed && k.shootHeld && k.aim);
assert.ok(!k.pausePressed && !k.passPressed);
assert.deepEqual(a.move, { x: 0.8, z: 0 }); assert.ok(a.passPressed && !a.pausePressed && !a.shootHeld && !a.aim);
assert.deepEqual(b.move, { x: 0, z: 0.7 }); assert.ok(b.pausePressed && !b.passPressed && !b.shootHeld && !b.aim);
assert.deepEqual(finger.move, { x: 0.5, z: 0 }); assert.ok(!finger.pausePressed && !finger.shootHeld && !finger.passPressed);
keyboard.clearActions(); pointer('pointerup', 0); assert.ok(keyboard.poll().shootReleased);
keyboard.clearActions(); match.ball.owner = players[0]; pointer('pointerdown', 0);
assert.ok(keyboard.poll().passPressed && !k.shootPressed, 'team 1 mouse tackles when team 0 owns the ball');
key('keyup', 'KeyW');
assert.ok(a.passPressed, 'clearing keyboard edges does not consume pad edges');
pad0.clearActions(); assert.ok(!pad0.poll().passPressed);
pads[0] = null; assert.deepEqual(pad0.poll().move, { x: 0, z: 0 }); assert.equal(pad2.poll().move.z, 0.7);
pads[0] = makePad(); pads[0].buttons[1].pressed = true;
assert.ok(!pad0.poll().shootHeld, 'reconnection waits for release');
pads[0].buttons[1].pressed = false; assert.ok(!pad0.poll().shootReleased);
pads[0].buttons[1].pressed = true; assert.ok(pad0.poll().shootPressed);
pad0.reset(); assert.ok(!pad0.poll().shootHeld, 'a held menu button does not bleed into play');
pads[2].axes = [0, 0]; pads[2].buttons[9].pressed = false;
assert.ok(!pad2.padActive(), 'another pad cannot skip the opening');
console.log('Keyboard/mouse on team 1, two indexed pads, touch, retained edges and disconnect/reconnect are isolated.');
